"""
Teacher Dataset Loader

This dataset loader combines both:
1. Real videos encoded by teacher (Phase 1.1)
2. Synthetic videos generated by teacher (Phase 1.2)

For distillation training of a student model.

Usage:
    from data_proc.teacher_dataset import TeacherDataset
    
    dataset = TeacherDataset(
        real_data_dir="data/teacher_latents",
        synthetic_data_dir="data/teacher_synthetic",
        mode="both"  # "real", "synthetic", or "both"
    )
    
    for batch in dataset:
        video = batch['video']  # or None for real (already in latent space)
        z_teacher = batch['z_teacher']
        text_emb = batch['text_emb']
        text = batch['text']
        # ... train student model
"""

import os
import glob
import torch
from torch.utils.data import Dataset
import random


class TeacherDataset(Dataset):
    """Dataset loader for teacher-encoded and teacher-generated data."""
    
    def __init__(
        self,
        real_data_dir=None,
        synthetic_data_dir=None,
        mode="both",
        max_trajectory_steps=None,
        shuffle=True,
    ):
        """
        Args:
            real_data_dir: Directory with encoded real videos (.pt files)
            synthetic_data_dir: Directory with generated videos (subdirs with generation_data.pt)
            mode: "real", "synthetic", or "both"
            max_trajectory_steps: If not None, limit trajectory to this many steps
            shuffle: Whether to shuffle the dataset
        """
        super().__init__()
        
        self.mode = mode
        self.max_trajectory_steps = max_trajectory_steps
        
        self.samples = []
        
        # Load real video paths
        if mode in ["real", "both"] and real_data_dir is not None:
            if os.path.exists(real_data_dir):
                real_files = glob.glob(os.path.join(real_data_dir, "*.pt"))
                for path in real_files:
                    self.samples.append({
                        'type': 'real',
                        'path': path
                    })
                print(f"Loaded {len(real_files)} real video samples from {real_data_dir}")
            else:
                print(f"Warning: real_data_dir not found: {real_data_dir}")
        
        # Load synthetic video paths
        if mode in ["synthetic", "both"] and synthetic_data_dir is not None:
            if os.path.exists(synthetic_data_dir):
                synthetic_count = 0
                for item_dir in os.listdir(synthetic_data_dir):
                    item_path = os.path.join(synthetic_data_dir, item_dir)
                    if os.path.isdir(item_path):
                        gen_data_path = os.path.join(item_path, "generation_data.pt")
                        if os.path.exists(gen_data_path):
                            self.samples.append({
                                'type': 'synthetic',
                                'path': gen_data_path
                            })
                            synthetic_count += 1
                print(f"Loaded {synthetic_count} synthetic video samples from {synthetic_data_dir}")
            else:
                print(f"Warning: synthetic_data_dir not found: {synthetic_data_dir}")
        
        if len(self.samples) == 0:
            raise ValueError("No samples found! Check your data directories.")
        
        if shuffle:
            random.shuffle(self.samples)
        
        print(f"Total samples: {len(self.samples)} ({mode} mode)")
    
    def __len__(self):
        return len(self.samples)
    
    def __getitem__(self, idx):
        sample_info = self.samples[idx]
        sample_type = sample_info['type']
        path = sample_info['path']
        
        # Load data
        data = torch.load(path, map_location='cpu')
        
        # Prepare output dict
        output = {
            'type': sample_type,
            'path': path,
        }
        
        if sample_type == 'real':
            # Real video (already encoded to latents)
            output['z_teacher'] = data['z_teacher']
            output['text_emb'] = data['text_emb']
            output['text_attention_mask'] = data['text_attention_mask']
            output['video'] = None  # No RGB video, only latents
            output['text'] = None  # Text not stored in encoded data
            output['trajectory'] = None
            
            if 'text_emb_2' in data:
                output['text_emb_2'] = data['text_emb_2']
                output['text_attention_mask_2'] = data['text_attention_mask_2']
        
        elif sample_type == 'synthetic':
            # Synthetic video (generated from text)
            output['video'] = data['generated_video']
            output['z_teacher'] = data['final_latents']
            output['text_emb'] = data['text_emb']
            output['text_attention_mask'] = data['text_attention_mask']
            output['text'] = data['text']
            
            if 'text_emb_2' in data:
                output['text_emb_2'] = data['text_emb_2']
                output['text_attention_mask_2'] = data['text_attention_mask_2']
            
            # Include trajectory if available
            trajectory = data.get('latents_trajectory', None)
            if trajectory is not None and self.max_trajectory_steps is not None:
                # Sample or truncate trajectory
                if len(trajectory) > self.max_trajectory_steps:
                    # Sample evenly across trajectory
                    indices = torch.linspace(0, len(trajectory) - 1, self.max_trajectory_steps).long()
                    trajectory = [trajectory[i] for i in indices]
            output['trajectory'] = trajectory
        
        return output
    
    def get_statistics(self):
        """Get dataset statistics."""
        stats = {
            'total_samples': len(self.samples),
            'real_samples': sum(1 for s in self.samples if s['type'] == 'real'),
            'synthetic_samples': sum(1 for s in self.samples if s['type'] == 'synthetic'),
        }
        return stats


def collate_teacher_data(batch):
    """
    Collate function for DataLoader.
    
    Handles variable-length trajectories and optional fields.
    """
    # Separate by type for easier batching
    real_batch = [item for item in batch if item['type'] == 'real']
    synthetic_batch = [item for item in batch if item['type'] == 'synthetic']
    
    collated = {}
    
    if len(real_batch) > 0:
        collated['real'] = {
            'z_teacher': torch.stack([item['z_teacher'] for item in real_batch]),
            'text_emb': torch.cat([item['text_emb'] for item in real_batch], dim=0),
            'text_attention_mask': torch.cat([item['text_attention_mask'] for item in real_batch], dim=0),
        }
        
        # Optional CLIP embeddings
        if 'text_emb_2' in real_batch[0]:
            collated['real']['text_emb_2'] = torch.cat([item['text_emb_2'] for item in real_batch], dim=0)
            collated['real']['text_attention_mask_2'] = torch.cat([item['text_attention_mask_2'] for item in real_batch], dim=0)
    
    if len(synthetic_batch) > 0:
        collated['synthetic'] = {
            'video': torch.cat([item['video'] for item in synthetic_batch], dim=0),
            'z_teacher': torch.cat([item['z_teacher'] for item in synthetic_batch], dim=0),
            'text_emb': torch.cat([item['text_emb'] for item in synthetic_batch], dim=0),
            'text_attention_mask': torch.cat([item['text_attention_mask'] for item in synthetic_batch], dim=0),
            'text': [item['text'] for item in synthetic_batch],
            'trajectory': [item['trajectory'] for item in synthetic_batch],
        }
        
        # Optional CLIP embeddings
        if 'text_emb_2' in synthetic_batch[0]:
            collated['synthetic']['text_emb_2'] = torch.cat([item['text_emb_2'] for item in synthetic_batch], dim=0)
            collated['synthetic']['text_attention_mask_2'] = torch.cat([item['text_attention_mask_2'] for item in synthetic_batch], dim=0)
    
    return collated


